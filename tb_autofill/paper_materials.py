# 有账套数据即视为已取得；序时账单独判断
FROM_LEDGER = {"科目余额表（鼎信诺账套）"}


def for_paper(index_no, name, *, has_journal=False, category=""):
    """返回该科目的资料需求清单：[(名称, 用途, 提供方, 是否已取得)]。"""
    from .paper_pack import category as detect
    key = category or detect(index_no, name)
    items = list(COMMON) + list(_LIBRARY.get(key, _LIBRARY["asset"]))
    result, seen = [], set()
    for name_text, usage, source, ready in items:
        if name_text in seen:
            continue
        seen.add(name_text)
        if name_text in FROM_LEDGER:
            ready = True
        result.append({"name": name_text, "usage": usage, "source": source, "ready": bool(ready)})
    if has_journal:
        result.append({"name": "序时账（凭证分录）", "usage": "凭证抽查与截止性测试", "source": "鼎信诺账套",
                       "ready": True})
    return result


def pending(items):
    """未取得的资料名称列表。"""
    return [item["name"] for item in items if not item["ready"]]
